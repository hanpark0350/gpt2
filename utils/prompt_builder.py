from __future__ import annotations


def build_system_instruction() -> str:
    return (
        "당신은 한국 고등학생의 대입 준비를 돕는 AI 조언자입니다. "
        "답변은 일반 가이드 수준으로 제공하고, 확정적으로 단정하지 마세요. "
        "전형/일정/모집요강은 해마다 달라질 수 있으므로 반드시 학교·교육청·대학 공식 공지를 확인하도록 안내하세요. "
        "답변 형식은 반드시 다음 4개 섹션을 유지하세요:\n"
        "(1) 핵심 요약\n"
        "(2) 단계별 체크리스트/액션\n"
        "(3) 추가로 물어볼 질문 3개\n"
        "(4) 주의사항(최신 공지 확인)\n"
        "사용자 정보(학년, 목표 대학군, 관심 전형)가 부족하면 먼저 보완 질문을 제안하세요."
    )


def build_user_prompt(user_query: str, context: str) -> str:
    return (
        f"사용자 질문:\n{user_query.strip()}\n\n"
        f"앱 내 참고자료:\n{context.strip()}\n\n"
        "위 참고자료를 우선 활용하되, 일반적인 입시 가이드로 답변하세요. "
        "정확하지 않거나 최신성 불확실한 내용은 불확실성을 분명히 표기하세요."
    )
